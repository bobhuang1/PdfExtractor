//! The test counts the documentation states are the suite's own.
//!
//! `plan.md` records how many tests the workspace holds, how many end-to-end
//! tests `cli_test` runs, and how the golden binary's tests divide up. Those
//! numbers are useful only while they are true: a count copied by hand goes
//! stale the moment a test is added. This test asks Cargo for the current list
//! (`--list`, which does not run anything) and holds every documented count to
//! it.
//!
//! The check is itself one of the tests it counts. Adding it moved the
//! workspace total, so the plan states the new total; a later test added
//! without the same edit fails here, naming both numbers. The per-suite counts
//! are checked as well, because a test moving from one target to another can
//! leave the workspace total unchanged while making the plan wrong.
//!
//! The golden reference and baseline counts are held the same way: the number
//! of `docling/*.json` references the plan, README and golden README state must
//! equal the files on disk, and README's remembered baseline must equal the
//! entries in `compare-baseline.json`. The same files split those references in
//! two: a reference named after a document in `test-data/real` is a corpus
//! document, one that is not is a fixture beside the corpus (`test-data/*`).
//! Both counts, and the sum the reference count is made of, are read off the
//! disk, so an added or renamed document cannot leave the prose behind.
//!
//! The workspace total is the Unix suite, because `crates/ui/tests/job_test.rs`
//! is Unix-only. On another platform only that total is skipped; the target
//! counts below are the same everywhere.
//!
//! Run it alone with:
//!
//! ```text
//! cargo test -p pdfextractor-cli --test documentation_test
//! ```

use std::path::{Path, PathBuf};
use std::process::Command;

fn repository_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// The test names `cargo test <args> -- --list` prints.
///
/// The list is read rather than the source counted: a test generated by a
/// macro, or one behind a target's `cfg`, is a test only the harness knows
/// about, and this check is about what the suite actually contains.
fn listed_tests(root: &Path, args: &[&str]) -> Vec<String> {
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let output = Command::new(cargo)
        .current_dir(root)
        .args(args)
        // List with the features this test was built with: a build without
        // Tesseract cannot compile the default (OCR) feature set. The lists are
        // the same either way — an OCR test is ignored there, not removed.
        .args((!cfg!(feature = "ocr")).then_some("--no-default-features"))
        .args(["--locked", "--", "--list"])
        .output()
        .unwrap_or_else(|error| {
            panic!(
                "could not run `cargo test {} -- --list`: {error}",
                args.join(" ")
            )
        });
    assert!(
        output.status.success(),
        "`cargo test {} -- --list` failed:\n{}\n{}",
        args.join(" "),
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr),
    );

    String::from_utf8_lossy(&output.stdout)
        .lines()
        .filter_map(|line| line.strip_suffix(": test"))
        .map(str::to_string)
        .collect()
}

/// A count written as digits (`1,046`) or as an English word (`eight`).
///
/// Prose often carries the count inside punctuation — `(37 corpus documents` —
/// so the punctuation around the number is trimmed before it is read.
fn count_from(token: &str) -> Option<usize> {
    let token = token.trim_matches(|c: char| !c.is_alphanumeric() && c != ',' && c != '-');

    if let Ok(count) = token.replace(',', "").parse::<usize>() {
        return Some(count);
    }

    match token.split_once('-') {
        Some((tens, units)) => Some(word_value(tens)? + word_value(units)?),
        None => word_value(token),
    }
}

/// The value of one English number word, up to `ninety-nine`.
fn word_value(word: &str) -> Option<usize> {
    Some(match word {
        "zero" => 0,
        "one" => 1,
        "two" => 2,
        "three" => 3,
        "four" => 4,
        "five" => 5,
        "six" => 6,
        "seven" => 7,
        "eight" => 8,
        "nine" => 9,
        "ten" => 10,
        "eleven" => 11,
        "twelve" => 12,
        "thirteen" => 13,
        "fourteen" => 14,
        "fifteen" => 15,
        "sixteen" => 16,
        "seventeen" => 17,
        "eighteen" => 18,
        "nineteen" => 19,
        "twenty" => 20,
        "thirty" => 30,
        "forty" => 40,
        "fifty" => 50,
        "sixty" => 60,
        "seventy" => 70,
        "eighty" => 80,
        "ninety" => 90,
        _ => return None,
    })
}

/// The count after `prefix` in `text`, naming the file when it cannot be read.
fn count_after_in(text: &str, prefix: &str, source: &str) -> usize {
    let start = text
        .find(prefix)
        .unwrap_or_else(|| panic!("{source} no longer contains {prefix:?}"));
    let token = text[start + prefix.len()..]
        .split_whitespace()
        .next()
        .unwrap_or_default();
    count_from(token)
        .unwrap_or_else(|| panic!("{source}: {token:?} after {prefix:?} is not a count"))
}

/// The count before `marker` in `text`, naming the file when it cannot be read.
fn count_before_in(text: &str, marker: &str, source: &str) -> usize {
    let end = text
        .find(marker)
        .unwrap_or_else(|| panic!("{source} no longer contains {marker:?}"));
    let token = text[..end].split_whitespace().last().unwrap_or_default();
    count_from(token)
        .unwrap_or_else(|| panic!("{source}: {token:?} before {marker:?} is not a count"))
}

/// The count after `prefix` in the plan, e.g. `the suite holds 1,047 tests`.
fn count_after(plan: &str, prefix: &str) -> usize {
    count_after_in(plan, prefix, "plan.md")
}

/// The count before `marker` in the plan, e.g. `128 end-to-end tests`.
fn count_before(plan: &str, marker: &str) -> usize {
    count_before_in(plan, marker, "plan.md")
}

fn assert_count(what: &str, documented: usize, listed: usize) {
    assert_eq!(
        documented, listed,
        "plan.md says {what} is {documented}, but `cargo test -- --list` lists {listed}.\n\
         Update the documented count in the same change as the suite."
    );
}

/// The file stems directly inside `dir`, ignoring directories.
fn document_stems(dir: &Path) -> Vec<String> {
    let mut stems: Vec<String> = std::fs::read_dir(dir)
        .unwrap_or_else(|error| panic!("could not read {}: {error}", dir.display()))
        .flatten()
        .map(|entry| entry.path())
        .filter(|path| path.is_file())
        .filter_map(|path| {
            path.file_stem()
                .map(|stem| stem.to_string_lossy().into_owned())
        })
        .collect();
    stems.sort();
    stems
}

/// The stems of the committed Docling references (`test-data/golden/docling/*.json`).
fn reference_stems(root: &Path) -> Vec<String> {
    let dir = root.join("test-data/golden/docling");
    let mut stems: Vec<String> = std::fs::read_dir(&dir)
        .unwrap_or_else(|error| panic!("could not read {}: {error}", dir.display()))
        .flatten()
        .map(|entry| entry.path())
        .filter(|path| path.extension().and_then(|ext| ext.to_str()) == Some("json"))
        .filter_map(|path| {
            path.file_stem()
                .map(|stem| stem.to_string_lossy().into_owned())
        })
        .collect();
    stems.sort();
    stems
}

/// The number of committed Docling references (`test-data/golden/docling/*.json`).
fn reference_count(root: &Path) -> usize {
    reference_stems(root).len()
}

/// The corpus documents (`test-data/real`), every one of which must have a
/// reference.
fn corpus_document_count(root: &Path) -> usize {
    let corpus = document_stems(&root.join("test-data/real"));
    let references = reference_stems(root);
    let missing: Vec<&String> = corpus
        .iter()
        .filter(|stem| !references.iter().any(|name| name == *stem))
        .collect();
    assert!(
        missing.is_empty(),
        "the golden set has no Docling reference for corpus document(s) {missing:?}"
    );
    corpus.len()
}

/// The references that name no corpus document — the fixtures beside the corpus
/// (`inventory.xlsx`, `q3_review_impress.odp`, …) — each of which must be a file
/// committed under `test-data/`.
fn fixture_count(root: &Path) -> usize {
    let corpus = document_stems(&root.join("test-data/real"));
    let fixtures: Vec<String> = reference_stems(root)
        .into_iter()
        .filter(|stem| !corpus.contains(stem))
        .collect();
    let present = document_stems(&root.join("test-data"));
    let missing: Vec<&String> = fixtures
        .iter()
        .filter(|stem| !present.iter().any(|name| name == *stem))
        .collect();
    assert!(
        missing.is_empty(),
        "these Docling references name no fixture under test-data/: {missing:?}"
    );
    fixtures.len()
}

/// The number of documents the ratchet baseline remembers.
fn baseline_document_count(root: &Path) -> usize {
    let path = root.join("test-data/golden/compare-baseline.json");
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("could not read {}: {error}", path.display()));
    let baseline: serde_json::Value = serde_json::from_str(&text)
        .unwrap_or_else(|error| panic!("could not parse {}: {error}", path.display()));
    baseline
        .get("documents")
        .and_then(serde_json::Value::as_object)
        .map(|documents| documents.len())
        .unwrap_or(0)
}

/// Hold a documented reference or baseline count to the repository's own.
fn assert_repository_count(what: &str, source: &str, documented: usize, actual: usize) {
    assert_eq!(
        documented, actual,
        "{source} says {what} is {documented}, but the repository has {actual}.\n\
         Update the documented count in the same change as the references or the baseline."
    );
}

#[test]
fn documented_test_counts_match_the_test_list() {
    let root = repository_root();
    let plan_path = root.join("plan.md");
    let plan = std::fs::read_to_string(&plan_path)
        .unwrap_or_else(|error| panic!("could not read {}: {error}", plan_path.display()));
    let readme_path = root.join("README.md");
    let readme = std::fs::read_to_string(&readme_path)
        .unwrap_or_else(|error| panic!("could not read {}: {error}", readme_path.display()));
    let golden_readme_path = root.join("test-data/golden/README.md");
    let golden_readme = std::fs::read_to_string(&golden_readme_path)
        .unwrap_or_else(|error| panic!("could not read {}: {error}", golden_readme_path.display()));
    let references = reference_count(&root);
    let baseline_documents = baseline_document_count(&root);
    let corpus_documents = corpus_document_count(&root);
    let fixtures = fixture_count(&root);
    assert!(
        references > 0 && baseline_documents > 0 && corpus_documents > 0 && fixtures > 0,
        "a reference, baseline, corpus or fixture count came back empty, so this check \
         would pass without checking anything"
    );
    assert_eq!(
        references,
        corpus_documents + fixtures,
        "the {references} committed references are not the {corpus_documents} corpus \
         documents plus the {fixtures} fixtures beside them"
    );

    let workspace = listed_tests(&root, &["test", "--workspace"]);
    let cli = listed_tests(
        &root,
        &["test", "-p", "pdfextractor-cli", "--test", "cli_test"],
    );
    let golden = listed_tests(
        &root,
        &[
            "test",
            "-p",
            "pdfextractor-cli",
            "--test",
            "docling_golden_test",
        ],
    );

    assert!(
        !workspace.is_empty() && !cli.is_empty() && !golden.is_empty(),
        "a test list came back empty, so this check would pass without checking anything"
    );

    // The golden binary's prose divides its tests by what they check. These are
    // the names those divisions are made from.
    let fixture_checks = golden
        .iter()
        .filter(|name| {
            name.ends_with("_conforms_to_the_docling_schema")
                && name.as_str() != "every_corpus_document_conforms_to_the_docling_schema"
        })
        .count();
    let comparison_units = golden
        .iter()
        .filter(|name| name.starts_with("comparison::"))
        .count();
    let acceptance_tests = golden
        .iter()
        .filter(|name| {
            matches!(
                name.as_str(),
                "docling_core_accepts_our_documents"
                    | "our_output_agrees_with_real_docling_conversions"
            )
        })
        .count();

    // `job_test.rs` is `#![cfg(unix)]`; the documented total is the Unix suite
    // the test gate runs, so another platform's smaller total is not drift.
    #[cfg(unix)]
    assert_count(
        "the workspace suite",
        count_after(&plan, "the suite holds "),
        workspace.len(),
    );
    #[cfg(not(unix))]
    println!(
        "skipped the workspace total on this platform: the suite lists {} tests, and the \
         documented total counts the Unix-only tests in `job_test`",
        workspace.len()
    );
    assert_count(
        "the `cli_test` suite",
        count_before(&plan, " end-to-end tests in `cli_test`"),
        cli.len(),
    );
    assert_count(
        "the golden binary",
        count_before(&plan, " tests in the binary"),
        golden.len(),
    );
    assert_count(
        "the golden fixture checks",
        count_before(&plan, " fixture checks"),
        fixture_checks,
    );
    assert_count(
        "the golden comparison units",
        count_before(&plan, " comparison units"),
        comparison_units,
    );
    assert_count(
        "the golden acceptance tests",
        count_before(&plan, " acceptance tests"),
        acceptance_tests,
    );

    assert_repository_count(
        "the committed Docling references",
        "plan.md",
        count_before(&plan, " real Docling conversions"),
        references,
    );
    assert_repository_count(
        "the committed Docling references",
        "README.md",
        count_before_in(&readme, " comparable references", "README.md"),
        references,
    );
    assert_repository_count(
        "the committed Docling references",
        "test-data/golden/README.md",
        count_after_in(&golden_readme, ") — **", "test-data/golden/README.md"),
        references,
    );
    assert_repository_count(
        "the baseline documents",
        "README.md",
        count_after_in(&readme, "docling · memory: ", "README.md"),
        baseline_documents,
    );
    assert_repository_count(
        "the corpus documents",
        "README.md",
        count_before_in(&readme, " corpus documents", "README.md"),
        corpus_documents,
    );
    assert_repository_count(
        "the corpus documents",
        "test-data/golden/README.md",
        count_after_in(
            &golden_readme,
            "every one of the ",
            "test-data/golden/README.md",
        ),
        corpus_documents,
    );
    assert_repository_count(
        "the fixtures beside the corpus",
        "test-data/golden/README.md",
        count_before_in(
            &golden_readme,
            "fixtures beside the corpus",
            "test-data/golden/README.md",
        ),
        fixtures,
    );
}
