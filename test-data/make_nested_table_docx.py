#!/usr/bin/env python3
"""Write test-data/nested_table.docx: the table-inside-a-cell fixture.

A purpose-built DOCX (an OPC package of XML parts, zipped) whose outer table
holds a `w:tbl` inside one of its cells, between two sentences of that cell:

  * the outer table is the only table of the *document*: three columns' worth of
    a two-column grid, a marked header row (`w:tblHeader`) and two body rows;
  * the second row's detail cell is prose, then a table of its own (a step and
    who owns it), then prose again — so the cell's own text is split around the
    nested table rather than only preceding it;
  * nothing else in the package is a table, and the table is the last thing in
    the document: a closing paragraph would be a second block the reference
    places after its table, and the comparison would pair the two paragraphs
    with one another rather than the two readings of the table.

A reading that treated the nested `w:tbl` as a second table standing beside the
outer one would put the checklist's words in the document order instead of the
cell's, and the outer cell would hold only the two sentences. This is the
fixture the comparison corpus holds Docling's reading against; its reference is
generated by `test-data/golden/regenerate.py`.

Regenerate the file with:

    python3 test-data/make_nested_table_docx.py

and the reference with:

    ~/.venvs/pdfextractor-docling/bin/python test-data/golden/regenerate.py \\
        nested_table.docx
"""

import zipfile

W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"

CONTENT_TYPES = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
  <Override PartName="/word/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/>
</Types>
"""

ROOT_RELS = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
</Relationships>
"""

# The styles part is what both readers take the heading from: the paragraph
# names the style ("Heading1") and the styles part says that style is a heading
# — Word's own outline level, not a name a reader has to recognise.
DOCUMENT_RELS = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>
</Relationships>
"""

STYLES = f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:styles xmlns:w="{W}">
  <w:docDefaults>
    <w:rPrDefault><w:rPr><w:sz w:val="22"/></w:rPr></w:rPrDefault>
  </w:docDefaults>
  <w:style w:type="paragraph" w:default="1" w:styleId="Normal">
    <w:name w:val="Normal"/>
  </w:style>
  <w:style w:type="paragraph" w:styleId="Heading1">
    <w:name w:val="heading 1"/>
    <w:basedOn w:val="Normal"/>
    <w:pPr><w:outlineLvl w:val="0"/></w:pPr>
  </w:style>
</w:styles>
"""


def paragraph(text, style=None):
    props = f"<w:pPr><w:pStyle w:val=\"{style}\"/></w:pPr>" if style else ""
    return f"<w:p>{props}<w:r><w:t>{text}</w:t></w:r></w:p>"


def cell(body, width):
    return f'<w:tc><w:tcPr><w:tcW w:w="{width}" w:type="dxa"/></w:tcPr>{body}</w:tc>'


def table(grid, rows):
    """A `w:tbl`: its grid in twips, and one string per row."""
    return (
        "<w:tbl>"
        + "<w:tblGrid>"
        + "".join(f'<w:gridCol w:w="{width}"/>' for width in grid)
        + "</w:tblGrid>"
        + "".join(rows)
        + "</w:tbl>"
    )


# The checklist: a step and who owns it, with short words so the comparison's
# per-cell checks stay about the reading rather than about their length.
NESTED = table(
    [1400, 1400],
    [
        "<w:tr>"
        + cell(paragraph("Step"), 1400)
        + cell(paragraph("Who"), 1400)
        + "</w:tr>",
        "<w:tr>"
        + cell(paragraph("Draft"), 1400)
        + cell(paragraph("Ana"), 1400)
        + "</w:tr>",
        "<w:tr>"
        + cell(paragraph("Sign off"), 1400)
        + cell(paragraph("Ivo"), 1400)
        + "</w:tr>",
    ],
)

# The cell the nested table lives in: a sentence, the table, then a sentence
# again — the cell's own text is on both sides of it.
DETAIL = (
    paragraph("The checklist below is a table inside this cell.")
    + NESTED
    + paragraph("Those steps are this cell's content too.")
)

OUTER = table(
    [1800, 5400],
    [
        "<w:tr><w:trPr><w:tblHeader/></w:trPr>"
        + cell(paragraph("Phase"), 1800)
        + cell(paragraph("Detail"), 5400)
        + "</w:tr>",
        "<w:tr>"
        + cell(paragraph("Review"), 1800)
        + cell(DETAIL, 5400)
        + "</w:tr>",
        "<w:tr>"
        + cell(paragraph("Publish"), 1800)
        + cell(paragraph("One sentence in the cell beside it."), 5400)
        + "</w:tr>",
    ],
)

DOCUMENT = f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="{W}">
<w:body>
{paragraph("Nested table", "Heading1")}
{paragraph("The table below sits inside one cell of the outer table, between two of that cell's sentences.")}
{OUTER}
<w:sectPr><w:pgSz w:w="11906" w:h="16838"/><w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440"/></w:sectPr>
</w:body>
</w:document>
"""


def main():
    path = "test-data/nested_table.docx"
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as package:
        # Fixed timestamps, so regenerating the fixture is byte for byte.
        def put(name, text):
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            package.writestr(info, text)

        put("[Content_Types].xml", CONTENT_TYPES)
        put("_rels/.rels", ROOT_RELS)
        put("word/_rels/document.xml.rels", DOCUMENT_RELS)
        put("word/styles.xml", STYLES)
        put("word/document.xml", DOCUMENT)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
